chmod +x "$KIT"/*.command "$KIT"/AIオフィス/*.command "$KIT"/skill/discord-ai-office/scripts/*.sh 2>/dev/null
xattr -dr com.apple.quarantine "$KIT" 2>/dev/null
echo "✓ キットを $KIT に置きました"
echo ""
echo "設定シートを開きます。サーバー名・bot の名前・社員名簿などを書き換えて保存（⌘S）してください。"
echo "そのままで良ければ何もしなくてOK。"
open -e "$KIT/設定シート.txt"
read -r -p "書き終わったら（またはそのままで）このターミナルに戻って Enter: " _
exec bash "$KIT/skill/discord-ai-office/scripts/setup_mac.sh" "$KIT"   # stdin はターミナルのまま（/dev/tty を付けると claude auth login が kqueue EINVAL で落ちる）
exit 0
