set -u
KIT="$HOME/ai-office-kit"
echo "=== AIオフィス インストール ==="
rm -rf "$KIT" "$HOME/.ai-office-kit.tmp"; mkdir -p "$HOME/.ai-office-kit.tmp"
awk '/^__PAYLOAD_BELOW__$/{f=1;next} f' "$0" | base64 -D > "$HOME/.ai-office-kit.tmp/kit.zip" || { echo "✗ 取り出しに失敗"; exit 1; }
